// Regenerates src/utils/assetManifest.generated.ts from the GLB files in
// public/models. Run with: node scripts/generate-asset-manifest.mjs
import fs from 'node:fs'
import path from 'node:path'

const root = path.resolve(import.meta.dirname, '..')
const modelsDir = path.join(root, 'public/models')
const playgroundReadme = path.join(root, 'Assets/LowPolyPlaygroundParkPack_v1.0/README.md')

// Real-world sizes (metres, x/y/z in Blender axes) from the playground pack README.
const sizes = {}
if (fs.existsSync(playgroundReadme)) {
  for (const line of fs.readFileSync(playgroundReadme, 'utf8').split('\n')) {
    const m = line.match(/^\|\s*(\w+)\s*\|[^|]+\|\s*\d+\s*\|\s*(\d+) x (\d+) x (\d+)\s*\|/)
    if (m) sizes[m[1]] = [m[2], m[3], m[4]].map((cm) => Number(cm) / 100)
  }
}

const cityCategory = (name) => {
  const prefix = name.split('_')[0]
  return (
    {
      Building: 'building', House: 'building',
      Car: 'vehicle', Vehicle: 'vehicle',
      Road: 'road', Sidewalk: 'road',
      Street: 'street', Planter: 'vegetation', Flowers: 'vegetation', Tree: 'vegetation',
      Park: 'ground', Playground: 'play', Sport: 'sport',
    }[prefix] ?? 'misc'
  )
}

const list = (dir) =>
  fs.readdirSync(path.join(modelsDir, dir)).filter((f) => f.endsWith('.glb')).sort()

const entries = []
for (const file of list('environment/playground')) {
  const id = file.replace('.glb', '')
  entries.push({ id, pack: 'playground', kind: 'environment', category: 'park', url: `/models/environment/playground/${file}`, draco: false, sizeM: sizes[id] })
}
for (const file of list('environment/city')) {
  const id = file.replace('.glb', '')
  entries.push({ id, pack: 'city', kind: 'environment', category: cityCategory(id), url: `/models/environment/city/${file}`, draco: true })
}
for (const file of list('characters')) {
  const id = file.replace('.glb', '')
  const clips = ['Idle', 'Walk', 'Run', 'Scared', ...(id.includes('Basketball') ? ['Dribble', 'Shoot'] : [])]
  entries.push({ id, pack: 'city', kind: 'character', category: 'character', url: `/models/characters/${file}`, draco: false, clips })
}

const out = `// AUTO-GENERATED by scripts/generate-asset-manifest.mjs — do not edit by hand.
import type { AssetEntry } from './assetTypes'

export const ASSETS: readonly AssetEntry[] = ${JSON.stringify(entries, null, 2)}
`
fs.writeFileSync(path.join(root, 'src/utils/assetManifest.generated.ts'), out)
console.log(`Wrote ${entries.length} assets`)
